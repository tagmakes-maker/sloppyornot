// Inlines the agent's prompts, schemas, and demo seed into src/prompts.js so the
// deployed worker has no filesystem dependency. Run: node scripts/build-prompts.mjs
// wrangler runs it before every dev and deploy (see [build] in wrangler.toml).
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..");
const read = (p) => readFileSync(join(root, p), "utf8");
const readJson = (p) => JSON.parse(read(p));

export function build() {
  const interview = read("agent/experts/interview.md");
  const block = interview.match(/```json\n([\s\S]*?)\n```/);
  if (!block) throw new Error("agent/experts/interview.md has no ```json question block");
  const questions = JSON.parse(block[1]);

  const out = {
    INTERVIEW_PROMPT: interview,
    INTERVIEW_QUESTIONS: questions,
    REVIEW_PROMPT: read("agent/prompts/expert-review.md"),
    EXPERT_PROFILE_SCHEMA: readJson("agent/experts/expert-profile.schema.json"),
    VALIDATION_SCHEMA: readJson("agent/experts/validation.schema.json"),
    PRODUCT_SCHEMA: readJson("shared/profile.schema.json"),
    DEMO_PRODUCT: readJson("seed/floodwatch-chs.json"),
  };

  let js = "// GENERATED by scripts/build-prompts.mjs from agent/, shared/, and seed/. Do not edit.\n";
  for (const [name, value] of Object.entries(out)) {
    js += `export const ${name} = ${JSON.stringify(value, null, 2)};\n`;
  }
  return js;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(here, "..", "src", "prompts.js"), build());
  console.log("wrote src/prompts.js");
}
